def plugin_manifest(path, installed_app=None):
    product = PRODUCTS['agent']
    executable_name = product['executable']
    app_name = product['name'] + '.app'
    if installed_app:
        app = shlex.quote(str(installed_app))
        exe = shlex.quote(str(pathlib.Path(installed_app) / 'Contents/MacOS' / executable_name))
        report = f'{exe} --record-session'
        command = report + f'; /usr/bin/open -g {app}'
    else:
        locate = (
            f'APP="/Applications/{app_name}"; '
            f'[ -x "$APP/Contents/MacOS/{executable_name}" ] || APP="$HOME/Applications/{app_name}"; '
            f'[ -x "$APP/Contents/MacOS/{executable_name}" ] || APP="$HOME/Library/Application Support/{product["name"]}/{app_name}"; '
        )
        report = locate + f'if [ -x "$APP/Contents/MacOS/{executable_name}" ]; then "$APP/Contents/MacOS/{executable_name}" --record-session; fi'
        command = locate + f'if [ -x "$APP/Contents/MacOS/{executable_name}" ]; then "$APP/Contents/MacOS/{executable_name}" --record-session; /usr/bin/open -g "$APP"; fi'
    # SessionStart launches the app; the remaining lifecycle events only report
    # context. The app watches that report, so a per-turn event never has to open
    # anything and stays a one-shot process. Tool-level events are deliberately not
    # registered: they fire thousands of times per session and would slow the host.
    lifecycle = ['Stop', 'StopFailure', 'SessionEnd', 'SubagentStart', 'SubagentStop', 'PreCompact', 'PostCompact']
    hooks = [{'event': 'SessionStart', 'command': command, 'timeout': 10}]
    hooks += [{'event': event, 'command': report, 'timeout': 5} for event in lifecycle]
    manifest = {'name': 'kimi-stats-hud', 'version': product['version'],
                'description': 'Agent Stats 的 Kimi Code 启动入口与会话生命周期上下文。统一应用同时支持 Codex、Kimi Code；插件移除不会卸载应用。',
                'license': 'MIT', 'interface': {'displayName': product['name'], 'shortDescription': 'Codex、Kimi Code 统一原生统计'},
                'hooks': hooks}
    path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    return manifest


